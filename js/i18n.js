export const SUPPORTED_LANGUAGES = [
  { code: 'en', name: 'English', nativeName: 'English' },
  { code: 'hi', name: 'Hindi', nativeName: 'हिंदी' },
  { code: 'mr', name: 'Marathi', nativeName: 'मराठी' }
];

const STORAGE_LANG_KEY = 'pragati_selected_lang';

export function getCurrentLanguage() {
  const saved = localStorage.getItem(STORAGE_LANG_KEY);
  if (saved && TRANSLATIONS[saved]) {
    return saved;
  }
  return 'en';
}

export function t(key, fallback = '') {
  const lang = getCurrentLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}

export function translateStatus(status) {
  if (!status) return '';
  const key = `status_${status.toLowerCase().replace(/[\s-]/g, '_')}`;
  return t(key, status);
}

export function translateTrade(trade) {
  if (!trade) return '';
  const clean = trade.toLowerCase();
  if (clean.includes('civil')) return t('trade_civil', trade);
  if (clean.includes('mep')) return t('trade_mep', trade);
  if (clean.includes('steel') || clean.includes('peb')) return t('trade_steel', trade);
  if (clean.includes('concrete') || clean.includes('precast')) return t('trade_concrete', trade);
  if (clean.includes('highway') || clean.includes('road')) return t('trade_highway', trade);
  if (clean.includes('waterproofing')) return t('trade_waterproofing', trade);
  if (clean.includes('interior')) return t('trade_interior', trade);
  if (clean.includes('facade')) return t('trade_facade', trade);
  if (clean.includes('demolition')) return t('trade_demolition', trade);
  if (clean.includes('plumbing')) return t('trade_plumbing', trade);
  if (clean.includes('electrical')) return t('trade_electrical', trade);
  if (clean.includes('painting')) return t('trade_painting', trade);
  if (clean.includes('flooring')) return t('trade_flooring', trade);
  if (clean.includes('roofing')) return t('trade_roofing', trade);
  if (clean.includes('landscaping')) return t('trade_landscaping', trade);
  return trade;
}

export function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) {
    console.warn(`Language ${lang} not supported. Defaulting to en.`);
    lang = 'en';
  }

  localStorage.setItem(STORAGE_LANG_KEY, lang);
  document.documentElement.lang = lang;
  
  // Apply to DOM
  applyTranslations();

  // Dispatch global event for reactive listeners (navbars, charts, modals)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  console.log(`🌐 Pragati Connect language switched to: ${lang}`);
}

export function applyTranslations(root = document) {
  const lang = getCurrentLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  // 1. Inner Text replacement via data-i18n
  const textElements = root.querySelectorAll('[data-i18n]');
  textElements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translatedText = dict[key] || TRANSLATIONS.en[key];
    if (translatedText) {
      // Check if element contains child icons, spinners or sub-elements
      const icons = Array.from(el.querySelectorAll(':scope > i, :scope > svg, :scope > .spinner-border'));
      if (icons.length > 0) {
        const firstEl = el.firstElementChild;
        const lastEl = el.lastElementChild;
        const hasIconBefore = firstEl && icons.includes(firstEl);
        const hasIconAfter = lastEl && lastEl !== firstEl && icons.includes(lastEl);
        const clonedIcons = icons.map(ic => ic.cloneNode(true));
        
        el.innerHTML = '';
        if (hasIconBefore && hasIconAfter) {
          el.appendChild(clonedIcons[0]);
          el.appendChild(document.createTextNode(' ' + translatedText + ' '));
          el.appendChild(clonedIcons[clonedIcons.length - 1]);
        } else if (hasIconAfter && !hasIconBefore) {
          el.appendChild(document.createTextNode(translatedText + ' '));
          clonedIcons.forEach(ic => el.appendChild(ic));
        } else {
          clonedIcons.forEach(ic => el.appendChild(ic));
          el.appendChild(document.createTextNode(' ' + translatedText));
        }
      } else {
        el.textContent = translatedText;
      }
    }
  });

  // 2. Placeholders replacement via data-i18n-ph
  const placeholderElements = root.querySelectorAll('[data-i18n-ph]');
  placeholderElements.forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    const translatedText = dict[key] || TRANSLATIONS.en[key];
    if (translatedText) {
      el.setAttribute('placeholder', translatedText);
    }
  });

  // 3. Title / tooltip replacement via data-i18n-title
  const titleElements = root.querySelectorAll('[data-i18n-title]');
  titleElements.forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translatedText = dict[key] || TRANSLATIONS.en[key];
    if (translatedText) {
      el.setAttribute('title', translatedText);
    }
  });
}
